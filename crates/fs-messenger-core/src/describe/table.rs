//! THE capability table: every capability id of `requirements.md` and of the core, with the command (or field) that
//! carries it, its kind, input, whether the core can do it, and why not.
//!
//! Pattern: Registry (a `static` table read by `types.rs`, the Backend and the tests). It is the only place that says
//! what is supported. When `types.capnp` has the field `supported` on a command, `support::apply_support` is the one
//! function that starts to set it; the table does not change. A test fails when an id of `requirements.md` is missing.

